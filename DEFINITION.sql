-- HOW TO CREATE DATABASE:

-- CONSTRAINTS (RULE) IN MYSQL
-- DATA INTEGRITY AND VALIDATION


-- 1. NOT NULL: NO NULL VALUES ARE ACCEPTED 
/* NAME VARCHAR(50) NOT NULL */

-- 2. UNIQUE: NO DUPLICATE RECORDS ARE ALLOWED 
/* EMAIL VARCHAR(100) UNIQUE*/

-- 3. PRIMARY KEY - UNIQUELY IDENTIFIES EACH ROW IN THE TABLE 
/* EMPLOYEE_ID INT PRIMARY KEY;*/


/*4. FOREIGN KEY : LINK ONE TABLE WITH ANOTHER 
TABLE ENFORCING 
REFERENTIAL INTEGRITY */



/* FOREIGN KEY 
EMP TABLE(DEPARTMENT_ID)
REFERENCE DEPARTMENTS(DEPARTMENT_ID)*/



CREATE DATABASE PS;
USE PS;
CREATE TABLE DEPARTMENTS
(
DEPARTMENT_ID INT PRIMARY KEY,
DEPARTMENT_NAME VARCHAR(100)
);
CREATE TABLE EMP
(
ID INT PRIMARY KEY,
NAME VARCHAR(100),
DEPARTMENT_ID INT,
FOREIGN KEY (DEPARTMENT_ID)
REFERENCE DEPARTMENTS(DEPARTMENT_ID));

DESCRIBE EMP;
DESCRIBE DEPARTMENTS;


